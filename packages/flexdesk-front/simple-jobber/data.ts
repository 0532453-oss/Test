/**
 * Helper to extract scheduledDate, scheduledStartTime, scheduledEndTime from datetime
 */
function extractScheduleFields(startAt: Date | null, endAt: Date | null) {
  if (!startAt || !endAt) {
    return {
      scheduledDate: null,
      scheduledStartTime: null,
      scheduledEndTime: null,
    };
  }
  return {
    scheduledDate: format(startAt, 'yyyy-MM-dd'),
    scheduledStartTime: format(startAt, 'HH:mm'),
    scheduledEndTime: format(endAt, 'HH:mm'),
  };
}

