import {
  BadRequestException,
  Controller,
  Get,
  Param,
  ParseUUIDPipe,
  Post,
  Body,
  Query,
  Req,
} from '@nestjs/common';
import {
  ApiTags,
  ApiOperation,
  ApiResponse,
  ApiQuery,
  ApiParam,
  ApiBearerAuth,
} from '@nestjs/swagger';
import { type Request } from 'express';

import {
  type CustomerPortalService,
  type CustomerPortalData,
  type InvoiceSummary,
  type JobSummary,
  type PortalTokenResult,
} from './customer-portal.service';
import { type GeneratePortalTokenDto } from './dto/generate-portal-token.dto';

import { Public } from '@/modules/auth/decorators/public.decorator';
import { type PaymentLinkResult } from '@/modules/billing/stripe-manager/stripe.service';

/**
 * Customer Portal Controller
 *
 * Provides public endpoints for customers to view their invoices and job history.
 * Access is controlled via signed tokens that are generated by admin users.
 *
 * Public endpoints (no JWT required):
 * - GET /customer-portal?token=xxx - Get full portal data
 * - GET /customer-portal/invoices?token=xxx - Get all invoices
 * - GET /customer-portal/invoices/:id?token=xxx - Get single invoice
 * - GET /customer-portal/jobs?token=xxx - Get all jobs
 * - GET /customer-portal/jobs/:id?token=xxx - Get single job
 *
 * Admin endpoints (JWT required):
 * - POST /customer-portal/generate-token - Generate portal access token
 */
@ApiTags('customer-portal')
@Controller('customer-portal')
export class CustomerPortalController {
  constructor(private readonly portalService: CustomerPortalService) {}

  // ============================================
  // Admin Endpoints (require JWT authentication)
  // ============================================

  @Post('generate-token')
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Generate a portal access token for a customer' })
  @ApiResponse({ status: 201, description: 'Token generated successfully' })
  @ApiResponse({ status: 404, description: 'Customer not found' })
  async generateToken(
    @Body() dto: GeneratePortalTokenDto,
  ): Promise<PortalTokenResult> {
    return this.portalService.generatePortalToken(
      dto.customerId,
      dto.workspaceId,
      dto.expiryDays,
    );
  }

  // ============================================
  // Public Endpoints (no JWT required)
  // ============================================

  @Get()
  @Public()
  @ApiOperation({ summary: 'Get customer portal data (invoices and jobs)' })
  @ApiQuery({ name: 'token', required: true, description: 'Portal access token' })
  @ApiResponse({ status: 200, description: 'Portal data returned' })
  @ApiResponse({ status: 401, description: 'Invalid or expired token' })
  async getPortalData(
    @Req() req: Request,
    @Query('token') queryToken: string,
  ): Promise<CustomerPortalData> {
    const token = this.extractToken(req, queryToken);

    const payload = this.portalService.verifyToken(token);
    return this.portalService.getPortalData(payload.customerId, payload.workspaceId);
  }

  @Get('invoices')
  @Public()
  @ApiOperation({ summary: 'Get all invoices for customer' })
  @ApiQuery({ name: 'token', required: true, description: 'Portal access token' })
  @ApiResponse({ status: 200, description: 'Invoices returned' })
  @ApiResponse({ status: 401, description: 'Invalid or expired token' })
  async getInvoices(
    @Req() req: Request,
    @Query('token') queryToken: string,
  ): Promise<InvoiceSummary[]> {
    const token = this.extractToken(req, queryToken);

    const payload = this.portalService.verifyToken(token);
    const data = await this.portalService.getPortalData(
      payload.customerId,
      payload.workspaceId,
    );
    return data.invoices;
  }

  @Get('invoices/:id')
  @Public()
  @ApiOperation({ summary: 'Get a single invoice by ID' })
  @ApiParam({ name: 'id', description: 'Invoice UUID' })
  @ApiQuery({ name: 'token', required: true, description: 'Portal access token' })
  @ApiResponse({ status: 200, description: 'Invoice returned' })
  @ApiResponse({ status: 401, description: 'Invalid or expired token' })
  @ApiResponse({ status: 404, description: 'Invoice not found' })
  async getInvoiceById(
    @Param('id', ParseUUIDPipe) id: string,
    @Req() req: Request,
    @Query('token') queryToken: string,
  ): Promise<InvoiceSummary> {
    const token = this.extractToken(req, queryToken);

    const payload = this.portalService.verifyToken(token);
    return this.portalService.getInvoiceById(
      id,
      payload.customerId,
      payload.workspaceId,
    );
  }

  @Get('jobs')
  @Public()
  @ApiOperation({ summary: 'Get all jobs for customer' })
  @ApiQuery({ name: 'token', required: true, description: 'Portal access token' })
  @ApiResponse({ status: 200, description: 'Jobs returned' })
  @ApiResponse({ status: 401, description: 'Invalid or expired token' })
  async getJobs(
    @Req() req: Request,
    @Query('token') queryToken: string,
  ): Promise<JobSummary[]> {
    const token = this.extractToken(req, queryToken);

    const payload = this.portalService.verifyToken(token);
    const data = await this.portalService.getPortalData(
      payload.customerId,
      payload.workspaceId,
    );
    return data.jobs;
  }

  @Get('jobs/:id')
  @Public()
  @ApiOperation({ summary: 'Get a single job by ID' })
  @ApiParam({ name: 'id', description: 'Job UUID' })
  @ApiQuery({ name: 'token', required: true, description: 'Portal access token' })
  @ApiResponse({ status: 200, description: 'Job returned' })
  @ApiResponse({ status: 401, description: 'Invalid or expired token' })
  @ApiResponse({ status: 404, description: 'Job not found' })
  async getJobById(
    @Param('id', ParseUUIDPipe) id: string,
    @Req() req: Request,
    @Query('token') queryToken: string,
  ): Promise<JobSummary> {
    const token = this.extractToken(req, queryToken);

    const payload = this.portalService.verifyToken(token);
    return this.portalService.getJobById(
      id,
      payload.customerId,
      payload.workspaceId,
    );
  }

  @Post('invoices/:id/pay')
  @Public()
  @ApiOperation({ summary: 'Generate a payment link for an invoice' })
  @ApiParam({ name: 'id', description: 'Invoice UUID' })
  @ApiQuery({ name: 'token', required: true, description: 'Portal access token' })
  @ApiResponse({ status: 201, description: 'Payment link generated' })
  @ApiResponse({ status: 400, description: 'Invoice already paid or Stripe not configured' })
  @ApiResponse({ status: 401, description: 'Invalid or expired token' })
  @ApiResponse({ status: 404, description: 'Invoice not found' })
  async getPaymentLink(
    @Param('id', ParseUUIDPipe) id: string,
    @Req() req: Request,
    @Query('token') queryToken: string,
  ): Promise<PaymentLinkResult> {
    const token = this.extractToken(req, queryToken);

    const payload = this.portalService.verifyToken(token);
    return this.portalService.getInvoicePaymentLink(
      id,
      payload.customerId,
      payload.workspaceId,
    );
  }

  private extractToken(req: Request, queryToken?: string): string {
    const token = req.headers.authorization?.replace('Bearer ', '') || queryToken;
    if (!token) {
      throw new BadRequestException('Portal access token is required');
    }
    return token;
  }
}
