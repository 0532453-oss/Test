/** Helper: extract scheduledDate (YYYY-MM-DD), scheduledStartTime (HH:mm), scheduledEndTime (HH:mm) from Date objects */
function sched(startAt: Date | null, endAt: Date | null) {
  if (!startAt) return { scheduledDate: null, scheduledStartTime: null, scheduledEndTime: null };
  return {
    scheduledDate: format(startAt, 'yyyy-MM-dd'),
    scheduledStartTime: format(startAt, 'HH:mm'),
    scheduledEndTime: endAt ? format(endAt, 'HH:mm') : null,
  };
}

